    def get_random_post(
        self,
        persona: dict,
        topic: str = None,
    ) -> str:
        """
        根据人格获取随机朋友圈文案。

        Args:
            persona: 人格档案字典
            topic: 指定主题，None 则根据人格自动选择

        Returns:
            朋友圈文案
        """
        persona_id = persona.get("id", "")

        if topic is None:
            # 从人格的 topics 中随机选一个
            persona_topics = persona.get("topics", ["日常"])
            # 映射到模板主题
            mapped_topics = []
            for pt in persona_topics:
                for tpl_topic in self.TEMPLATES.keys():
                    if pt in persona.get("hobbies", []) or tpl_topic in persona_topics:
                        mapped_topics.append(tpl_topic)
            if not mapped_topics:
                mapped_topics = list(self.TEMPLATES.keys())
            topic = random.choice(list(set(mapped_topics)))

        # 从该主题选取文案
        templates = self.TEMPLATES.get(topic, self.TEMPLATES["日常"])
        template = random.choice(templates)

        return template

    def get_all_topics(self) -> list[str]:
        """获取所有文案主题"""
        return list(self.TEMPLATES.keys())
